"""Reproduce exact historical files in the approved Agent build, never new scores.

Default is read-only validation. CI must explicitly opt in to restoration. No
existing differing file is overwritten, no extra destination entry is accepted,
and no approval/source/native fingerprint is regenerated by this helper.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path

try:
    from . import risk_acceptance as risk
except ImportError:
    import risk_acceptance as risk

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = 'docs/evidence/optimization-20261026/historical-build-inputs'
DESTINATION = 'backend/evals/results'
FROZEN_APPROVAL_SHA256 = '1882516ae1b258e1019768b1d011b76774f184da905ac3c4b4970697736e260f'
FILENAMES = frozenset({
    'business-v5-fixed.json', 'business-v5.json', 'java-api-v5-current.json', 'java-api-v5.json',
    'rag-public-source-regression-2026-09-01.stderr.log', 'rag-public-source-regression-2026-09-01.stdout.log',
    'rag-static-v1-current-2026-09-01.json', 'rag-static-v1-current-2026-09-01.md',
    'rag-static-v1-current-2026-09-01.stderr.log', 'rag-static-v1-current-2026-09-01.stdout.log',
    'travel-rag-static-v1-1-dense-chroma-2026-08-31.json', 'travel-rag-static-v1-1-dense-chroma-2026-08-31.md'})


def checked_path(root, relative):
    if not isinstance(relative, str) or Path(relative).is_absolute() or '..' in Path(relative).parts:
        raise RuntimeError('Historical input path must be an exact repository-relative allowlisted path')
    target = root / relative
    if not target.resolve().is_relative_to(root.resolve()):
        raise RuntimeError('Historical input path escapes repository')
    for path in [target, *target.parents]:
        if path == root.parent:
            break
        if path.is_symlink():
            raise RuntimeError('Historical input source/destination symlink refused')
    return target


def verify(root):
    root = root.resolve()
    approval_path = checked_path(root, '.github/security-risk-acceptance.json')
    if risk.digest(approval_path.read_bytes()) != FROZEN_APPROVAL_SHA256:
        raise RuntimeError('Frozen approval changed; historical inputs must be reviewed, never rebaselined')
    approval = json.loads(approval_path.read_text(encoding='utf-8'))
    manifest_path = checked_path(root, EVIDENCE + '/manifest.json')
    manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
    if (manifest.get('schema_version') != 1 or manifest.get('historical_only') is not True
            or manifest.get('fresh_evaluation') is not False or manifest.get('approved_business_revision') != risk.APPROVED_REVISION
            or manifest.get('approved_image_id') != risk.APPROVED_IMAGE or manifest.get('approval_sha256') != FROZEN_APPROVAL_SHA256
            or manifest.get('application_hash_algorithm') != risk.APPLICATION_HASH_ALGORITHM):
        raise RuntimeError('Historical input manifest does not preserve the approved artifact and evidence boundary')
    entries = manifest.get('files')
    if not isinstance(entries, list) or len(entries) != len(FILENAMES):
        raise RuntimeError('Exactly the twelve reviewed historical build inputs are required')
    seen, validated = set(), []
    for entry in entries:
        destination = entry.get('destination', '')
        name = Path(destination).name
        if (name not in FILENAMES or name in seen or destination != DESTINATION + '/' + name
                or entry.get('source') != EVIDENCE + '/evals-results/' + name
                or entry.get('image_path') != '/app/evals/results/' + name):
            raise RuntimeError('Historical input source/destination is outside the exact allowlist')
        seen.add(name)
        source = checked_path(root, entry['source']); target = checked_path(root, destination)
        if not source.is_file():
            raise RuntimeError('Historical build input missing: ' + name)
        raw = source.read_bytes()
        expected = approval['approved_image']['application_file_sha256'].get(entry['image_path'])
        if (len(raw) != entry.get('bytes') or risk.digest(raw) != entry.get('raw_sha256')
                or not expected or expected != entry.get('approved_application_sha256')
                or risk.application_digest(entry['image_path'], raw) != expected):
            raise RuntimeError('Historical input raw/approved application bytes differ: ' + name)
        if target.exists() and (not target.is_file() or target.read_bytes() != raw):
            raise RuntimeError('Existing historical destination differs; refusing overwrite: ' + name)
        validated.append((source, target, raw))
    destination = checked_path(root, DESTINATION)
    if destination.exists():
        if not destination.is_dir():
            raise RuntimeError('Historical build destination is not a directory')
        for path in destination.iterdir():
            if path.name not in FILENAMES or not path.is_file() or path.is_symlink():
                raise RuntimeError('Extra historical destination entry blocks faithful reproduction')
    return validated


def restore(root, restore_for_ci=False):
    if restore_for_ci and os.environ.get('GITHUB_ACTIONS', '').lower() != 'true':
        raise RuntimeError('Historical input copying requires explicit --restore-for-ci and GITHUB_ACTIONS=true')
    entries = verify(root)
    restored, existing = 0, 0
    for source, destination, raw in entries:
        if destination.exists():
            existing += 1
            continue
        if restore_for_ci:
            destination.parent.mkdir(parents=True, exist_ok=True)
            with destination.open('xb') as output:
                output.write(raw); output.flush(); os.fsync(output.fileno())
            restored += 1
    if restore_for_ci:
        verify(root)  # Check the complete copied destination; preserve on failure.
    return {'status': 'restored_exact_historical_inputs' if restore_for_ci else 'read_only_inputs_verified',
            'historical_only': True, 'fresh_evaluation': False, 'files_verified': len(entries),
            'files_restored': restored, 'existing_byte_identical': existing,
            'missing_destination_before_check': len(entries) - existing,
            'approval_sha256': FROZEN_APPROVAL_SHA256, 'fingerprints_changed': False,
            'boundary': 'Faithful historical build-input reproduction only; original artifact inclusion disclosed. No benchmark/provider execution and no new quality claim.'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--restore-for-ci', action='store_true')
    parser.add_argument('--report', type=Path)
    args = parser.parse_args()
    try:
        result = restore(ROOT, args.restore_for_ci)
    except Exception as error:
        result = {'status': 'blocked', 'error_type': type(error).__name__, 'message': str(error), 'fresh_evaluation': False}
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(json.dumps(result, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(result))
    return 1 if result['status'] == 'blocked' else 0


if __name__ == '__main__':
    raise SystemExit(main())
